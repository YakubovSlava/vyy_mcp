"""The machine-managed `launcher/` folder written into the child repo.

Everything a user needs to run an MCP server against that repo's skills,
kept in one self-contained directory:

    launcher/
      jupyter_mcp_tools/   this package's sources, copied in
      requirements.txt     third-party dependencies only
      src/main.py          starts the MCP server over stdio
      README.md            how to run it

**No part of this project is fetched from the network.** An earlier version
of this module pointed `requirements.txt` at `git+<repo>` so every run got
the newest logic; per explicit request that's gone. The package's own
sources are copied into the folder instead, so a clone contains everything
of ours and running it never reaches GitHub (or any other origin) for our
code.

Third-party libraries (`mcp`, `fastapi`, `uvicorn`, ...) are still installed
from PyPI by `pip`, as the user chose — vendoring those would mean ~93 MB of
platform-specific wheels in git. So the guarantee is specifically: *our*
sources are self-sufficient; dependencies resolve normally.

The copy is refreshed on every push, so the folder can't silently drift from
the code that generated it.
"""
from __future__ import annotations

import shutil
from pathlib import Path

LAUNCHER_DIR_NAME = "launcher"
ENTRYPOINT_RELPATH = f"{LAUNCHER_DIR_NAME}/src/main.py"
REQUIREMENTS_RELPATH = f"{LAUNCHER_DIR_NAME}/requirements.txt"
README_RELPATH = f"{LAUNCHER_DIR_NAME}/README.md"
# Where the package sources land inside the launcher folder. `main.py` puts
# this directory on `sys.path`, so the vendored copy is imported without
# installing anything.
VENDORED_PACKAGE_NAME = "jupyter_mcp_tools"
VENDORED_PACKAGE_RELDIR = f"{LAUNCHER_DIR_NAME}/{VENDORED_PACKAGE_NAME}"

_ENTRYPOINT = '''"""Start an MCP server serving the skills in this repository.

Generated by jupyter-mcp-tools and rewritten on every push -- edit the
owning project instead, changes here are lost.

Runs over stdio: an MCP client spawns this file as its "command" and talks
to it for the length of a session. `--shared-dir` points at the repository
root (two levels above `launcher/src/`), which is where `tools/` lives.

    pip install -r launcher/requirements.txt
    python launcher/src/main.py

Nothing of this project is downloaded at run time: `launcher/jupyter_mcp_tools/`
holds its sources, and this file puts that directory first on `sys.path`, so
the vendored copy is what gets imported. Only third-party dependencies come
from PyPI, via `pip install` above.
"""
from __future__ import annotations

import sys
from pathlib import Path

# `launcher/` -- one level above `src/`. Inserted at position 0 so the
# vendored sources win over any coincidentally installed copy of the package.
_LAUNCHER_DIR = Path(__file__).resolve().parents[1]
if str(_LAUNCHER_DIR) not in sys.path:
    sys.path.insert(0, str(_LAUNCHER_DIR))

from jupyter_mcp_tools.mcp_server.server import main  # noqa: E402

if __name__ == "__main__":
    repo_root = Path(__file__).resolve().parents[2]
    sys.argv = [sys.argv[0], "--transport", "stdio", "--shared-dir", str(repo_root), *sys.argv[1:]]
    main()
'''

_README = """# launcher/

Runs an MCP server serving the skills in this repository.

Generated by jupyter-mcp-tools; rewritten on every push, so don't hand-edit
anything in here.

```bash
pip install -r requirements.txt
python src/main.py
```

Then point an MCP client at `python src/main.py` (stdio transport) — it
serves `tools/` from the repository root.

## What is and isn't downloaded

`jupyter_mcp_tools/` holds this project's own sources, copied in at push
time — running the server never fetches them from a git remote. Only the
third-party dependencies listed in `requirements.txt` are installed from
PyPI (or your configured index).
"""


def package_source_root() -> Path | None:
    """Locate the `jupyter_mcp_tools` package directory to copy.

    Works for an editable install (package sits in a source checkout) and
    for a regular install (package sits in site-packages) alike — in both
    cases `__file__` points at a real directory with the sources.
    """
    try:
        import jupyter_mcp_tools
    except Exception:  # noqa: BLE001 - nothing to vendor if it can't import
        return None

    package_dir = Path(jupyter_mcp_tools.__file__).resolve().parent
    return package_dir if package_dir.is_dir() else None


def _iter_sources(package_dir: Path):
    """Every file worth shipping: no tests, no caches, no build metadata."""
    for path in sorted(package_dir.rglob("*")):
        if not path.is_file():
            continue
        parts = path.relative_to(package_dir).parts
        if "__pycache__" in parts or "tests" in parts:
            continue
        if path.suffix == ".pyc":
            continue
        yield path


def requirements_text() -> str:
    """Third-party dependencies only — no self-reference.

    The dependency list comes from the installed distribution's metadata
    rather than a hardcoded copy, so it can't drift from what this process
    actually runs with. If the metadata is unavailable, fall back to a
    minimal known-good set instead of writing an empty file that would fail
    at install time.
    """
    try:
        from importlib.metadata import requires

        declared = requires("jupyter-mcp-tools") or []
    except Exception:  # noqa: BLE001 - metadata is best-effort
        declared = []

    lines = ["# Generated by jupyter-mcp-tools -- do not edit.",
             "# This project's own sources are in ./jupyter_mcp_tools/; only",
             "# third-party dependencies are installed from an index."]
    deps: list[str] = []
    for requirement in declared:
        if "extra ==" in requirement:
            continue
        if requirement.lower().startswith("jupyter-mcp-tools"):
            continue
        deps.append(requirement)

    if not deps:
        deps = [
            "mcp>=1.6,<2",
            "fastapi>=0.110",
            "uvicorn[standard]>=0.29",
            "jinja2>=3.1",
            "python-multipart>=0.0.9",
            "requests>=2.31",
            "pexpect>=4.9",
        ]

    lines.extend(sorted(deps))
    return "\n".join(lines) + "\n"


def render() -> dict[str, str]:
    """The small text files this folder owns."""
    return {
        REQUIREMENTS_RELPATH: requirements_text(),
        ENTRYPOINT_RELPATH: _ENTRYPOINT,
        README_RELPATH: _README,
    }


def _write_if_changed(path: Path, content: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _sync_package(shared_dir: Path, package_dir: Path) -> None:
    """Mirror the package into `launcher/jupyter_mcp_tools/`.

    Mirrors rather than merely copies: a module deleted upstream must
    disappear here too, otherwise a stale file keeps being importable and
    the launcher runs code that no longer exists in the source of truth.
    Files are written only when their bytes differ, so an unchanged package
    produces no diff and therefore no commit.
    """
    destination = shared_dir / VENDORED_PACKAGE_RELDIR
    wanted: set[Path] = set()

    for source in _iter_sources(package_dir):
        relative = source.relative_to(package_dir)
        target = destination / relative
        wanted.add(target)
        payload = source.read_bytes()
        if target.exists() and target.read_bytes() == payload:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)

    if destination.is_dir():
        for existing in sorted(destination.rglob("*"), reverse=True):
            if existing.is_file() and existing not in wanted:
                existing.unlink()
            elif existing.is_dir() and not any(existing.iterdir()):
                existing.rmdir()


def ensure(shared_dir: Path) -> None:
    """Write the launcher folder, touching only what actually changed."""
    for relative, content in render().items():
        _write_if_changed(shared_dir / relative, content)

    package_dir = package_source_root()
    if package_dir is not None and package_dir.name == VENDORED_PACKAGE_NAME:
        _sync_package(shared_dir, package_dir)
