"""The machine-managed `launcher/` folder written into the child repo.

Everything a user needs to run an MCP server against that repo's skills,
kept in one self-contained directory:

    launcher/
      requirements.txt   third-party deps + this package itself
      src/main.py        starts the MCP server over stdio
      README.md          how to run it

Per explicit request the folder is **rewritten on every push** so it always
contains the current logic — "автоматически забиралась последняя версия".
That's why `requirements.txt` pulls the package from its git repo instead
of a vendored copy: a vendored copy is a snapshot that goes stale, while a
git reference resolves to whatever is current when the user installs.

It is app-owned, like `tools/` and `groups.json`: the admin UI refuses to
edit or delete it (see `common/repo_files.py`), because hand edits would be
silently overwritten by the next push.
"""
from __future__ import annotations

from pathlib import Path

LAUNCHER_DIR_NAME = "launcher"
ENTRYPOINT_RELPATH = f"{LAUNCHER_DIR_NAME}/src/main.py"
REQUIREMENTS_RELPATH = f"{LAUNCHER_DIR_NAME}/requirements.txt"
README_RELPATH = f"{LAUNCHER_DIR_NAME}/README.md"

# Where `requirements.txt` resolves this package from. Overridden per
# deployment with JUPYTER_MCP_TOOLS_PACKAGE_REPO_URL so a fork doesn't need
# a code change.
DEFAULT_PACKAGE_REPO_URL = "https://github.com/YakubovSlava/vyy_mcp.git"

_ENTRYPOINT = '''"""Start an MCP server serving the skills in this repository.

Generated by jupyter-mcp-tools and rewritten on every push -- edit the
admin UI (or this project's source) instead, changes here are lost.

Runs over stdio: an MCP client spawns this file as its "command" and talks
to it for the length of a session. `--shared-dir` points at the repository
root, one level above `launcher/`, which is where `tools/` lives.

    pip install -r launcher/requirements.txt
    python launcher/src/main.py
"""
from __future__ import annotations

import sys
from pathlib import Path

from jupyter_mcp_tools.mcp_server.server import main

if __name__ == "__main__":
    repo_root = Path(__file__).resolve().parents[2]
    sys.argv = [sys.argv[0], "--transport", "stdio", "--shared-dir", str(repo_root), *sys.argv[1:]]
    main()
'''

_README = """# launcher/

Runs an MCP server serving the skills in this repository.

Generated by jupyter-mcp-tools; rewritten on every push, so don't hand-edit
anything in here.

```bash
pip install -r requirements.txt
python src/main.py
```

Then point an MCP client at `python src/main.py` (stdio transport) — it
serves `tools/` from the repository root.

`requirements.txt` installs `jupyter-mcp-tools` from its git repository, so
running this always uses the current version of the server rather than a
snapshot.
"""


def package_repo_url() -> str:
    import os

    return os.environ.get("JUPYTER_MCP_TOOLS_PACKAGE_REPO_URL", DEFAULT_PACKAGE_REPO_URL).strip()


def requirements_text() -> str:
    """Third-party deps plus this package, resolved from git.

    The dependency list comes from the *installed* distribution's metadata
    rather than a hardcoded copy, so it can't drift from what this process
    actually runs with. If the metadata is unavailable (unusual install),
    fall back to a minimal known-good set rather than writing an empty file
    that would fail at install time.
    """
    try:
        from importlib.metadata import requires

        declared = requires("jupyter-mcp-tools") or []
    except Exception:  # noqa: BLE001 - metadata is best-effort
        declared = []

    lines: list[str] = [f"# Generated by jupyter-mcp-tools -- do not edit."]
    deps = []
    for requirement in declared:
        # Skip extras markers that pip would evaluate against the *user's*
        # environment (e.g. `; extra == "dev"`), and the self-reference if
        # one is ever declared.
        if "extra ==" in requirement:
            continue
        if requirement.lower().startswith("jupyter-mcp-tools"):
            continue
        deps.append(requirement)

    if not deps:
        deps = ["mcp>=1.6,<2", "fastapi>=0.110", "uvicorn[standard]>=0.29", "jinja2>=3.1", "requests>=2.31", "pexpect>=4.9"]

    lines.extend(sorted(deps))
    # Always the current logic, per explicit request: a git reference
    # resolves to whatever is on the default branch at install time.
    lines.append(f"jupyter-mcp-tools @ git+{package_repo_url()}")
    return "\n".join(lines) + "\n"


def render() -> dict[str, str]:
    """Every file this folder owns, as {repo-relative path: content}."""
    return {
        REQUIREMENTS_RELPATH: requirements_text(),
        ENTRYPOINT_RELPATH: _ENTRYPOINT,
        README_RELPATH: _README,
    }


def ensure(shared_dir: Path) -> None:
    """Write the launcher folder, rewriting only files whose content moved.

    The "only when changed" rule matters for the same reason it does
    elsewhere here: `push_shared_dir` runs on every skill install, and
    rewriting identical content would manufacture a commit each time.
    """
    for relative, content in render().items():
        path = shared_dir / relative
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
