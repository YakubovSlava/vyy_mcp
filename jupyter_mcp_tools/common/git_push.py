"""Pushes the shared tools directory's git history after a skill is added.

Per explicit request: the shared directory is assumed to already be a git
repository with its remote already configured — this project only runs
`git add`/`commit`/`push` in it; it never creates the repo or touches the
remote configuration itself.

The push step runs under a real pseudo-terminal (via `pexpect`) and types
the admin-configured username/password in response to git's own
"Username for ..."/"Password for ..." prompts, exactly as if someone had
typed them at an interactive terminal. This is a deliberate fallback per
explicit request after `GIT_ASKPASS`/`core.askpass` (see git history)
didn't work against this org's Bitbucket Server — some corporate git
setups apparently don't go through the normal askpass/credential-helper
path at all, so the only thing left that's guaranteed to work the same
way a human's manual `git push` does is emulating that human at a real
terminal.

Pushing is best-effort: a failure here must never block the skill install
that triggered it, only surface as a non-fatal detail in the response.
"""
from __future__ import annotations

import logging
import os
import re
import shutil
import subprocess
from pathlib import Path

import pexpect

logger = logging.getLogger("jupyter_mcp_tools.git_push")

_TIMEOUT_SECONDS = 30
_PROMPT_RE = re.compile(r"(username|password|логин|пароль)", re.IGNORECASE)

# Fallback only: used by `run.sh` when `_vendor/` isn't present (an older
# push from before vendoring existed, or this push ran from a non-
# editable install with no source tree to copy — see
# `_package_source_root()`). Override with
# JUPYTER_MCP_TOOLS_PACKAGE_REPO_URL if you've forked this project.
DEFAULT_PACKAGE_REPO_URL = "https://github.com/YakubovSlava/vyy_mcp.git"

_RUN_SCRIPT_NAME = "run.sh"
_GITIGNORE_NAME = ".gitignore"
_GITIGNORE_LINES = (
    ".run-venv/",
    # `pip install -e _vendor` drops its own build metadata next to
    # pyproject.toml inside _vendor/ -- the vendored *package* itself
    # (_vendor/jupyter_mcp_tools/) is wiped and recopied on every push
    # regardless, but this sits alongside it and would otherwise just
    # accumulate as noise in every future commit.
    "_vendor/*.egg-info/",
)
_VENDOR_DIR_NAME = "_vendor"
_VENDORED_PACKAGE_NAME = "jupyter_mcp_tools"
_VENDOR_SIDECAR_FILES = ("pyproject.toml", "requirements.txt")

_RUN_SCRIPT_TEMPLATE = """#!/usr/bin/env bash
# Auto-generated by jupyter-mcp-tools' git-push step (common/git_push.py)
# every time an admin saves a skill through the admin UI -- don't hand-
# edit, it's overwritten on the next push.
#
# Launches an MCP server serving exactly the skills committed in this
# repository (this script's own directory), with no separate hosting:
# an MCP client spawns this script and talks to it over stdio for the
# session. This repo is meant to be absolutely self-sufficient: the
# server's own source code is vendored into `_vendor/` right alongside
# the skills (see `_ensure_vendored_package()`), so running this never
# needs to reach the main source repo over the network -- only PyPI,
# for this project's own third-party dependencies (fastapi, uvicorn,
# ...), same as installing any other Python package.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
VENV_DIR="$SCRIPT_DIR/.run-venv"
VENDOR_DIR="$SCRIPT_DIR/{vendor_dir_name}"

if [ ! -x "$VENV_DIR/bin/python" ]; then
  python3 -m venv "$VENV_DIR"
fi

if [ -d "$VENDOR_DIR" ]; then
  "$VENV_DIR/bin/pip" install -q -e "$VENDOR_DIR"
else
  # Only reached for a shared_dir pushed before vendoring existed, or
  # pushed from a non-editable install with no source tree to vendor.
  PACKAGE_REPO_URL="${{JUPYTER_MCP_TOOLS_PACKAGE_REPO_URL:-{package_repo_url}}}"
  "$VENV_DIR/bin/pip" install -q "git+$PACKAGE_REPO_URL"
fi

exec "$VENV_DIR/bin/jupyter-mcp-tools-server" \\
  --transport stdio \\
  --shared-dir "$SCRIPT_DIR" \\
  "$@"
"""


def _render_run_script() -> str:
    return _RUN_SCRIPT_TEMPLATE.format(package_repo_url=DEFAULT_PACKAGE_REPO_URL, vendor_dir_name=_VENDOR_DIR_NAME)


def _ensure_run_script(shared_dir: Path) -> None:
    """Write/refresh `run.sh` in `shared_dir` so every push always ships
    a way to launch a server straight from this repo, with no separate
    hosting needed — see the template above. Only rewrites the file when
    its content actually changed, so a push with no other changes still
    correctly has "nothing to commit"."""
    path = shared_dir / _RUN_SCRIPT_NAME
    content = _render_run_script()
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")
    path.chmod(0o755)


def _ensure_gitignore(shared_dir: Path) -> None:
    """Make sure `run.sh`'s own build/run artifacts (created the first
    time someone actually runs it from a clone) never get committed —
    see `_GITIGNORE_LINES` above for what and why."""
    path = shared_dir / _GITIGNORE_NAME
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    existing_lines = existing.splitlines()
    missing = [line for line in _GITIGNORE_LINES if line not in existing_lines]
    if not missing:
        return
    separator = "\n" if existing and not existing.endswith("\n") else ""
    path.write_text(existing + separator + "\n".join(missing) + "\n", encoding="utf-8")


def _package_source_root() -> Path | None:
    """Locate the source checkout this running process's own
    `jupyter_mcp_tools` package was loaded from, if it's an editable
    install (the package directory sitting directly inside a checkout
    that also has `pyproject.toml`) — the only case there's actual
    source on disk to copy. A non-editable install (a built wheel) has
    no such tree; callers must handle `None` by skipping vendoring."""
    import jupyter_mcp_tools

    pkg_dir = Path(jupyter_mcp_tools.__file__).resolve().parent
    repo_root = pkg_dir.parent
    if (repo_root / "pyproject.toml").is_file():
        return repo_root
    return None


def _ensure_vendored_package(shared_dir: Path) -> None:
    """Copy this project's own source (the `jupyter_mcp_tools` package
    plus `pyproject.toml`/`requirements.txt`) into `shared_dir/_vendor/`,
    so `run.sh` can `pip install -e` it directly with no network
    dependency on the main source repo at all — making a git-push-
    configured shared_dir genuinely self-sufficient, not just a thin
    wrapper that still fetches code from elsewhere at run time.

    A no-op (leaves any existing `_vendor/` alone) if this process isn't
    running from an editable install — there's nothing to copy, and
    `run.sh`'s fallback to `pip install git+...` covers that case.
    """
    source_root = _package_source_root()
    if source_root is None:
        logger.info("not an editable install -- skipping package vendoring into %s", shared_dir)
        return

    vendor_dir = shared_dir / _VENDOR_DIR_NAME
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", ".ipynb_checkpoints")

    dest_pkg_dir = vendor_dir / _VENDORED_PACKAGE_NAME
    if dest_pkg_dir.exists():
        shutil.rmtree(dest_pkg_dir)
    shutil.copytree(source_root / _VENDORED_PACKAGE_NAME, dest_pkg_dir, ignore=ignore)

    for name in _VENDOR_SIDECAR_FILES:
        src = source_root / name
        if src.is_file():
            shutil.copy2(src, vendor_dir / name)


def _run(shared_dir: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(shared_dir), *args],
        capture_output=True,
        text=True,
        timeout=_TIMEOUT_SECONDS,
    )


def _run_under_pty_answering_credentials(
    argv: list[str], *, cwd: Path, username: str, password: str, extra_env: dict[str, str] | None = None
) -> str | None:
    """Run `argv` attached to a pseudo-terminal and type `username`/
    `password` in response to whatever "Username"/"Password" prompts it
    shows, the same way a human at a real terminal would. Returns an
    error string on failure, `None` on success (including when no prompt
    ever showed up at all)."""
    env = {**os.environ, **(extra_env or {})}
    try:
        child = pexpect.spawn(
            argv[0],
            argv[1:],
            cwd=str(cwd),
            env=env,
            timeout=_TIMEOUT_SECONDS,
            encoding="utf-8",
            codec_errors="replace",
        )
    except pexpect.exceptions.ExceptionPexpect as exc:
        return f"{argv[0]}: не удалось запустить псевдотерминал ({exc})"

    try:
        answers_sent = 0
        while answers_sent < 2:
            index = child.expect([_PROMPT_RE, pexpect.EOF, pexpect.TIMEOUT])
            if index != 0:
                break
            prompt = child.after.lower()
            if "pass" in prompt or "парол" in prompt:
                child.sendline(password)
            else:
                child.sendline(username)
            answers_sent += 1
        child.expect(pexpect.EOF, timeout=_TIMEOUT_SECONDS)
    except pexpect.exceptions.TIMEOUT:
        output = (child.before or "").strip()
        child.close(force=True)
        logger.warning("%s timed out waiting for a prompt in %s: %s", argv[0], cwd, output)
        return f"{argv[0]}: таймаут при ожидании ответа ({output[-300:]})" if output else f"{argv[0]}: таймаут"

    output = (child.before or "").strip()
    child.close()
    if child.exitstatus not in (0, None):
        logger.warning("%s failed in %s: %s", argv[0], cwd, output)
        return f"{argv[0]}: {output[-500:]}"
    return None


def push_shared_dir(shared_dir: Path, *, username: str, password: str, commit_message: str) -> str | None:
    """Add + commit + push whatever changed in `shared_dir`'s git repo.

    Returns `None` on success, or a short human-readable error string on
    failure (never raises).
    """
    if not (shared_dir / ".git").exists():
        return "общая директория не является git-репозиторием"

    _ensure_run_script(shared_dir)
    _ensure_gitignore(shared_dir)
    _ensure_vendored_package(shared_dir)

    try:
        _run(shared_dir, "add", "-A")
        # `git commit` exits 1 (indistinguishable from a real failure by
        # exit code alone) when there's nothing staged, and the message
        # saying so is locale-dependent -- checking for staged changes
        # first avoids parsing that text in any language.
        nothing_staged = _run(shared_dir, "diff", "--cached", "--quiet").returncode == 0
        if not nothing_staged:
            commit = _run(shared_dir, "commit", "-m", commit_message)
            if commit.returncode != 0:
                detail = (commit.stderr or commit.stdout).strip()
                logger.warning("git commit failed in %s: %s", shared_dir, detail)
                return f"git commit: {detail}"
    except subprocess.TimeoutExpired:
        logger.warning("git add/commit timed out in %s", shared_dir)
        return "git commit: превышено время ожидания"
    except OSError as exc:
        logger.warning("git add/commit could not run in %s: %s", shared_dir, exc)
        return f"git commit: {exc}"

    return _run_under_pty_answering_credentials(
        ["git", "-C", str(shared_dir), "push"],
        cwd=shared_dir,
        username=username,
        password=password,
        extra_env={"GIT_TERMINAL_PROMPT": "1"},
    )
